import type { Response } from 'express';
import PDFDocument from 'pdfkit';

interface ReportOptions {
  title: string;
  shopName: string;
  period: string;
  summary: { label: string; value: string }[];
  table?: { headers: string[]; rows: string[][]; widths?: number[] };
  footer?: string;
}

export function streamReportPdf(res: Response, options: ReportOptions) {
  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `inline; filename="${options.title.toLowerCase().replace(/\s+/g, '-')}.pdf"`
  );
  doc.pipe(res);

  const brand = '#101C2C';
  const gold = '#C69B4D';

  doc.rect(0, 0, doc.page.width, 90).fill(brand);
  doc.fillColor('#FFFFFF').fontSize(20).font('Helvetica-Bold').text(options.shopName, 48, 30);
  doc.fillColor(gold).fontSize(8).font('Helvetica').text('BUSINESS REPORT', 48, 58, { characterSpacing: 1.5 });
  doc.fillColor('#FFFFFF').fontSize(15).font('Helvetica-Bold').text(options.title, 300, 32, { width: 250, align: 'right' });
  doc.fillColor('#C5CDD9').fontSize(8).font('Helvetica').text(options.period, 300, 54, { width: 250, align: 'right' });

  let y = 120;
  doc.fillColor('#202938').fontSize(9).font('Helvetica-Bold').text('SUMMARY', 48, y);
  y += 16;

  const boxWidth = (doc.page.width - 96 - 12) / 2;
  options.summary.forEach((item, index) => {
    const column = index % 2;
    const row = Math.floor(index / 2);
    const x = 48 + column * (boxWidth + 12);
    const boxY = y + row * 42;
    doc.roundedRect(x, boxY, boxWidth, 34, 4).fillAndStroke('#F5F5F2', '#E9EDF2');
    doc.fillColor('#6E8099').fontSize(7).font('Helvetica').text(item.label.toUpperCase(), x + 10, boxY + 7, { width: boxWidth - 20 });
    doc.fillColor('#101C2C').fontSize(11).font('Helvetica-Bold').text(item.value, x + 10, boxY + 18, { width: boxWidth - 20 });
  });

  y += Math.ceil(options.summary.length / 2) * 42 + 12;

  const table = options.table;
  if (table && table.rows.length) {
    const widths = table.widths ?? table.headers.map(() => (doc.page.width - 96) / table.headers.length);
    doc.fillColor('#FFFFFF').rect(48, y, doc.page.width - 96, 22).fill(brand);
    let x = 48;
    doc.fontSize(7).font('Helvetica-Bold').fillColor('#FFFFFF');
    table.headers.forEach((header, index) => {
      doc.text(header.toUpperCase(), x + 6, y + 7, { width: widths[index] - 12 });
      x += widths[index];
    });
    y += 22;

    doc.font('Helvetica').fontSize(8).fillColor('#202938');
    table.rows.forEach((row, rowIndex) => {
      if (y > doc.page.height - 90) {
        doc.addPage();
        y = 48;
        doc.fillColor('#FFFFFF').rect(48, y, doc.page.width - 96, 22).fill(brand);
        let headerX = 48;
        doc.fontSize(7).font('Helvetica-Bold').fillColor('#FFFFFF');
        table.headers.forEach((header, index) => {
          doc.text(header.toUpperCase(), headerX + 6, y + 7, { width: widths[index] - 12 });
          headerX += widths[index];
        });
        y += 22;
        doc.font('Helvetica').fontSize(8).fillColor('#202938');
      }
      if (rowIndex % 2 === 0) doc.rect(48, y, doc.page.width - 96, 20).fill('#FAFAF8');
      let cellX = 48;
      doc.fillColor('#202938');
      row.forEach((cell, index) => {
        doc.text(String(cell), cellX + 6, y + 6, { width: widths[index] - 12, lineBreak: false });
        cellX += widths[index];
      });
      y += 20;
    });
  }

  doc
    .fontSize(7)
    .fillColor('#6E8099')
    .text(
      options.footer ?? `Generated by HILAAL on ${new Date().toLocaleString()}. Figures come from recorded transactions.`,
      48,
      doc.page.height - 60,
      { width: doc.page.width - 96, align: 'center' }
    );

  doc.end();
}
